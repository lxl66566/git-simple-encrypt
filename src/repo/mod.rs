pub const GIT_CONFIG_PREFIX: &str =
    const_str::replace!(concat!(env!("CARGO_CRATE_NAME"), "."), "_", "-");

/// Marker line embedded in every hook generated by git-se (the line right
/// below the shebang).
///
/// A unit test locks the template's second line to this constant so the
/// managed-hook detection cannot drift from the template.
const PRE_COMMIT_HOOK_MARKER: &[u8] = b"# Auto-generated by git-se install";

/// Build the pre-commit hook content that runs `git-se check --staged`
/// before every commit, so only files part of the current commit are
/// checked.
///
/// The hook invokes the running executable by absolute path (shell-quoted,
/// forward-slashed): a bare `git-se` would depend on PATH, and GUI clients
/// or CI images that never install it there would have every commit blocked
/// by a missing binary. This mirrors the absolute-path approach already
/// used for the filter driver config.
fn pre_commit_hook(exe_quoted: &str) -> Vec<u8> {
    format!(
        "#!/bin/sh\n{}\n{exe_quoted} check --staged\nif [ $? -ne 0 ]; then\n    echo \"Please run \
         'git-se e' to encrypt them before committing.\"\n    exit 1\nfi\n",
        String::from_utf8_lossy(PRE_COMMIT_HOOK_MARKER),
    )
    .into_bytes()
}

/// Whether the pre-commit hook at `hook_path` is managed by git-se
/// (recognized by the marker line below the shebang).
fn is_managed_hook(hook_path: &Path) -> Result<bool> {
    if !hook_path.exists() {
        return Ok(false);
    }
    let existing = std::fs::read(hook_path)?;
    Ok(existing
        .split(|&b| b == b'\n')
        .take(2) // shebang + marker line
        .any(|line| line.trim_ascii() == PRE_COMMIT_HOOK_MARKER))
}

/// Shell-quote an executable path for embedding in sh snippets and config
/// command lines: forward slashes work in both POSIX and MSYS sh, and single
/// quotes make everything else shell-safe.
fn quote_exe_for_sh(exe: &Path) -> String {
    let exe = exe.to_string_lossy().replace('\\', "/");
    format!("'{}'", exe.replace('\'', "'\\''"))
}

#[derive(Debug, Clone)]
pub struct Repo {
    /// The absolute worktree root this repo was opened from.
    ///
    /// Public for v3 source compatibility, but treat it as read-only: it
    /// must stay the absolute worktree root that [`Repo::open`] /
    /// [`Repo::discover`] validated, and mutating it bypasses that
    /// validation. There is intentionally no `Default` — a defaulted
    /// instance is an invalid one.
    pub path: PathBuf,
    pub conf: Config,
}

impl Repo {
    /// Open a repo. The `path` argument must be an absolute path.
    pub fn open(path: impl AsRef<Path>) -> Result<Self> {
        debug_assert!(path.as_ref().is_absolute(), "given path must be absolute");
        let mut repo_path = path.as_ref().to_path_buf();
        if !repo_path.exists() {
            return Err(Error::RepoNotFound(repo_path));
        }
        if !repo_path.is_dir() {
            return Err(Error::NotADirectory(repo_path));
        }
        if repo_path
            .file_name()
            .ok_or_else(|| Error::Other("Filename not found".to_string()))?
            == ".git"
        {
            repo_path.pop();
        }
        // A usable work tree must contain a `.git` entry: either a directory
        // (normal clone) or a `gitdir: <path>` pointer file (linked worktree /
        // submodule). Rejecting other directories up front avoids obscure git
        // errors from `get_key()`. The salt cache resolves such pointer files
        // to the real gitdir on its own (see `salt_cache::resolve_git_dir`),
        // so cache writes keep working from linked worktrees too.
        // No dedicated Error variant for v3 compatibility (the enum is not
        // `#[non_exhaustive]`); the message rides in `Error::Other`.
        let dot_git = repo_path.join(".git");
        if !dot_git.is_dir() && !dot_git.is_file() {
            return Err(Error::Other(format!(
                "not a git repository: {}",
                repo_path.display()
            )));
        }
        info!("Open repo: {}", repo_path.display());
        let config_file_path = repo_path.join(CONFIG_FILE_NAME);
        if !config_file_path.exists() {
            warn!(
                "Config file not found: `{}`, using default config instead...",
                config_file_path.display()
            );
        }
        // A GITSE-encrypted config (e.g. left behind by an `e .` from an
        // older release that did not exclude it) would hard-fail every
        // command — including the decrypt that could recover it. Fall back
        // to the default config instead so `git-se d` remains usable.
        let config_is_own_ciphertext = std::fs::read(&config_file_path).is_ok_and(|bytes| {
            bytes
                .first_chunk::<HEADER_LEN>()
                .is_some_and(has_gitse_magic)
        });
        let conf = if config_is_own_ciphertext {
            warn!(
                "Config file `{}` is encrypted (likely by an `e .` run); using the default config \
                 so the file can be decrypted back. Your settings return once it is restored.",
                config_file_path.display()
            );
            Config::default()
        } else {
            Config::load_or_default(&config_file_path).map_err(|e| Error::Config(e.to_string()))?
        }
        .with_repo_path(&repo_path);
        Ok(Self {
            path: repo_path,
            conf,
        })
    }

    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }

    pub fn to_absolute_path(&self, path: impl AsRef<Path>) -> PathBuf {
        self.path.join(path.as_ref())
    }

    /// Read the master key from git config.
    ///
    /// Returns an error if the key has not been configured. The returned
    /// string is zeroized on drop.
    pub fn get_key(&self) -> Result<Zeroizing<String>> {
        self.get_config("key").map(Zeroizing::new).map_err(|e| {
            Error::Other(format!(
                "Key not found, please run `git-se p` (or `git-se set key <VALUE>`) first: {e}"
            ))
        })
    }

    /// Set the key interactively by prompting on stdin.
    pub fn set_key_interactive(&self) -> Result<()> {
        let key = prompt_password("Please input your key: ")?;
        self.set_config("key", key.as_str())?;
        info!("Master key updated.");
        Ok(())
    }

    /// Check if all files in the crypt list (or given paths) are encrypted.
    ///
    /// When `staged` is true, only files staged for the current commit are
    /// checked, and their *staged blobs* are inspected — the blob is what
    /// the commit would actually write, so a worktree file that was
    /// encrypted, edited or deleted after staging cannot mask a staged
    /// plaintext (see [`Repo::check_staged`]). This is the mode the
    /// pre-commit hook uses.
    ///
    /// Returns `Ok(())` if all files are encrypted, or an error summarizing
    /// which files are not encrypted. The process exits with a non-zero code
    /// when files are not encrypted, suitable for CI usage.
    pub fn check(&self, paths: &[PathBuf], staged: bool) -> Result<()> {
        // In filter mode the working tree stays plaintext by design, so
        // checking worktree files would always fail and report nothing
        // useful. The staged check stays meaningful: it inspects the staged
        // blobs that will actually be committed.
        let filter_mode = self.filter_installed();
        if filter_mode && !staged {
            println!(
                "Filter integration is active: working-tree files stay plaintext and are \
                 encrypted automatically by git; only `check --staged` is meaningful (it inspects \
                 the staged blobs)."
            );
            return Ok(());
        }

        if staged {
            return self.check_staged();
        }

        let target_files = resolve_target_files(paths, &self.conf.crypt_list, self.path());
        if target_files.is_empty() {
            return Err(Error::NoFile("check"));
        }
        self.check_worktree(&target_files)
    }

    /// `check --staged`: inspect the staged blobs of crypt-list files.
    ///
    /// Enumeration uses `git diff --cached --name-only -z` (raw NUL-separated
    /// paths: `-z` disables C-quoting, so paths with `"`, backslashes,
    /// spaces or non-ASCII survive byte-for-byte) and membership is a plain
    /// prefix test against the crypt list. Blob contents come from
    /// `git ls-files -s` oids through a single [`CatFileBatch`] session —
    /// never from a per-file `exists()` worktree check, which used to drop
    /// staged files whose worktree copy had been deleted (F7a) and masked
    /// staged plaintext under an already-encrypted worktree file.
    fn check_staged(&self) -> Result<()> {
        let targets = self.staged_crypt_blobs()?;
        if targets.is_empty() {
            println!("No staged files need encryption check.");
            return Ok(());
        }

        println!(
            "\n{} {} {}",
            "Checking encryption status".bold(),
            format!("({} files)", targets.len()).cyan(),
            ":".dimmed()
        );

        let pb = Progress::new(targets.len(), "Check");
        let mut not_encrypted: Vec<String> = Vec::new();
        let mut first_error: Option<Error> = None;
        let mut batch = CatFileBatch::spawn(&self.path)?;
        for (rel, oid) in &targets {
            // The magic check only needs the leading header bytes; the rest
            // of the payload is drained without buffering, so staged blobs
            // of any size cost a fixed ~64-byte allocation.
            match batch.blob_prefix(oid, HEADER_LEN) {
                Ok(Some(head)) => {
                    if !is_ciphertext(&head) {
                        not_encrypted.push(rel.clone());
                    }
                },
                Ok(None) => warn!("staged blob {oid} of {rel} is missing from the object store"),
                Err(e) => {
                    warn!("Failed to read staged blob of {rel}: {e}");
                    first_error.get_or_insert(e);
                },
            }
            pb.inc(1);
        }
        pb.finish_and_clear();

        // Every error was logged above; surface the first one as the return value.
        if let Some(first) = first_error {
            return Err(first);
        }
        report_check(&not_encrypted, targets.len())
    }

    /// Check worktree files (manual/hook mode; filter mode never gets here).
    fn check_worktree(&self, target_files: &[PathBuf]) -> Result<()> {
        println!(
            "\n{} {} {}",
            "Checking encryption status".bold(),
            format!("({} files)", target_files.len()).cyan(),
            ":".dimmed()
        );

        let pb = Progress::new(target_files.len(), "Check");
        let not_encrypted: Mutex<Vec<String>> = Mutex::new(Vec::new());
        let errors: Mutex<Vec<Error>> = Mutex::new(Vec::new());

        parallel::for_each(target_files, |f| {
            match is_file_encrypted(f) {
                Ok(false) => {
                    let mut list = not_encrypted.lock();
                    let relative = pathdiff::diff_paths(f, &self.path).unwrap_or_else(|| f.clone());
                    list.push(relative.display().to_string());
                },
                Ok(true) => {},
                Err(e) => {
                    warn!("Failed to check {}: {e}", f.display());
                    errors.lock().push(e);
                },
            }
            pb.inc(1);
        });

        // Clear the progress bar on every exit path, error or not.
        pb.finish_and_clear();

        // Every error was logged above; surface the first one as the return value.
        if let Some(first) = errors.into_inner().into_iter().next() {
            return Err(first);
        }
        report_check(&not_encrypted.into_inner(), target_files.len())
    }

    /// Install a pre-commit hook that runs `git-se check` before each commit.
    ///
    /// Creates the pre-commit hook wherever git looks for hooks in this repo
    /// (a local `core.hooksPath` wins; otherwise the shared hooks dir of the
    /// common gitdir — linked worktrees read the main repository's hooks).
    /// Hooks previously installed by git-se (recognized by the marker line)
    /// are overwritten, so installing again also upgrades an outdated hook.
    /// Fails if a hook exists that is not managed by git-se.
    pub fn install_hook(&self) -> Result<()> {
        let (hooks_dir, foreign_hooks_path) = self.hooks_dir()?;
        std::fs::create_dir_all(&hooks_dir)?;

        let hook_path = hooks_dir.join("pre-commit");

        // An existing hook may only be overwritten when it is managed by
        // git-se (marker line below the shebang). Anything else is user
        // content and must be removed manually.
        if hook_path.exists() && !is_managed_hook(&hook_path)? {
            return Err(Error::HookExists(hook_path));
        }

        // Absolute exe path survives PATH changes; forward slashes work in
        // both POSIX sh and MSYS sh; single quotes make it shell-safe.
        let exe = std::env::current_exe()
            .map_err(|e| Error::Other(format!("failed to locate the running executable: {e}")))?;
        std::fs::write(&hook_path, pre_commit_hook(&quote_exe_for_sh(&exe)))?;

        // Set executable permission on unix. Windows users need Git for Windows
        // (msys-based) which executes the sh hook regardless of the executable
        // bit; a normal `write` is sufficient there.
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = std::fs::metadata(&hook_path)?.permissions();
            perms.set_mode(0o755);
            std::fs::set_permissions(&hook_path, perms)?;
        }

        println!(
            "{} pre-commit hook at {}",
            "Installed".green().bold(),
            hook_path.display()
        );
        if foreign_hooks_path {
            println!(
                "{}",
                "Note: core.hooksPath is set outside this repository (global/system scope); git \
                 may run hooks from there instead. Set a repo-local `git config core.hooksPath` \
                 if the hook does not trigger."
                    .yellow()
            );
        }
        Ok(())
    }

    /// Where git looks for hooks in this repository, plus whether a
    /// non-local `core.hooksPath` is in effect (the caller warns: the hook
    /// may be bypassed).
    ///
    /// 1. A repo-local `core.hooksPath` wins. Git resolves a relative value against the directory
    ///    it runs hooks from — the worktree root here. Only the LOCAL scope is honored: `git
    ///    rev-parse --git-path hooks` follows global `core.hooksPath` too, and writing a
    ///    repo-scoped hook into a hooks dir shared by every repository of that user would be far
    ///    worse than a warning.
    /// 2. Otherwise the hooks dir of the common gitdir (`git rev-parse --git-common-dir`): in a
    ///    linked worktree, hooks live in the MAIN repository's `.git/hooks`, not under the
    ///    worktree's private gitdir, so joining `.git/hooks` onto the worktree would install a hook
    ///    that is never read.
    fn hooks_dir(&self) -> Result<(PathBuf, bool)> {
        // Any non-local scope? (config precedence: local wins when both set)
        let foreign = self
            .run_with_output(&["config", "--get", "core.hooksPath"])
            .is_ok_and(|v| !v.trim().is_empty());
        if let Ok(local) = self.run_with_output(&["config", "--local", "--get", "core.hooksPath"]) {
            let local = local.trim();
            if !local.is_empty() {
                let path = PathBuf::from(local);
                let dir = if path.is_absolute() {
                    path
                } else {
                    self.path.join(path)
                };
                return Ok((dir, false));
            }
        }
        let common = self.run_with_output(&["rev-parse", "--git-common-dir"])?;
        let path = PathBuf::from(common.trim());
        let dir = if path.is_absolute() {
            path
        } else {
            self.path.join(path)
        };
        Ok((dir.join("hooks"), foreign))
    }

    /// Like [`Repo::open`], but walk up from `start` until a directory with a
    /// `.git` entry is found.
    ///
    /// Git runs the clean/smudge filter processes from the worktree root,
    /// but manual invocations from subdirectories should work too. This is
    /// a strict superset of `Repo::open` at the repo root, and every CLI
    /// command resolves its repo through here.
    pub fn discover(start: impl AsRef<Path>) -> Result<Self> {
        debug_assert!(start.as_ref().is_absolute(), "given path must be absolute");
        let mut dir = start.as_ref().to_path_buf();
        loop {
            let dot_git = dir.join(".git");
            if dot_git.is_dir() || dot_git.is_file() {
                return Self::open(&dir);
            }
            if !dir.pop() {
                return Err(Error::Other(format!(
                    "not a git repository: {}",
                    start.as_ref().display()
                )));
            }
        }
    }

    /// Whether the filter integration is installed in this repo: the
    /// clean/smudge drivers and/or the process filter.
    #[must_use]
    pub fn filter_installed(&self) -> bool {
        // `required` is written by every install of the filter mode; the
        // `process` check keeps this true for setups wired to the process
        // filter alone.
        self.get_raw_config(&format!("filter.{}.required", gitattributes::FILTER_NAME))
            .is_ok()
            || self
                .get_raw_config(&format!("filter.{}.process", gitattributes::FILTER_NAME))
                .is_ok()
    }

    /// Install the git filter integration: export `.gitattributes` and
    /// configure the clean/smudge filter driver plus the plaintext-diff
    /// textconv (transcrypt-style). After this, encryption and decryption
    /// are driven by git itself and the working tree stays plaintext.
    ///
    /// A git-se managed pre-commit hook is removed: it checks worktree
    /// files, which are plaintext on purpose in filter mode, so it would
    /// block every commit. Foreign hooks are kept (a warning is printed).
    pub fn install_filter(&self) -> Result<()> {
        // 0. Analyze the install-time migration before touching anything. Its `git checkout --force
        //    HEAD -- <paths>` resets the index as well as the worktree, so staged user changes on
        //    the affected paths must be surfaced as a hard error instead of being silently
        //    discarded.
        let has_key = self.get_key().is_ok();
        let plan = if has_key {
            Some(self.migration_plan()?)
        } else {
            None
        };
        if let Some(plan) = &plan
            && !plan.to_decrypt.is_empty()
            && self.has_staged_changes(&plan.to_decrypt)?
        {
            return Err(Error::Other(format!(
                "install would reset {} staged crypt-list file(s) via `git checkout --force HEAD \
                 --` (it rewrites the index too); commit them first or unstage them (`git restore \
                 --staged <path>`), then re-run install",
                plan.to_decrypt.len()
            )));
        }

        // Absolute exe path survives PATH changes; forward slashes work in
        // both POSIX sh and MSYS sh; single quotes make it shell-safe.
        let exe = std::env::current_exe()
            .map_err(|e| Error::Other(format!("failed to locate the running executable: {e}")))?;
        let quoted = quote_exe_for_sh(&exe);

        // 1. Export the managed .gitattributes block.
        let attr_path = self.path.join(".gitattributes");
        // Byte-oriented like every other .gitattributes touchpoint: the file
        // may legally hold non-UTF-8 pattern bytes (raw path bytes under
        // Unix), which a text read would reject.
        let content = match std::fs::read(&attr_path) {
            Ok(content) => content,
            // A missing .gitattributes is the common case: start from empty.
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
            // Any other read failure (permissions) must surface:
            // continuing with an empty base would clobber the user's file
            // with a block-only rewrite below.
            Err(e) => {
                return Err(Error::Other(format!(
                    "failed to read {}: {e}",
                    attr_path.display()
                )));
            },
        };
        let patterns = self.filter_patterns();
        let updated = gitattributes::with_managed_block(&content, &patterns);
        atomic_write(&attr_path, &updated)?;

        // 2. Configure the filter driver and the diff textconv.
        let f = format!("filter.{}", gitattributes::FILTER_NAME);
        self.set_raw_config(&format!("{f}.clean"), &format!("{quoted} clean %f"))?;
        self.set_raw_config(&format!("{f}.smudge"), &format!("{quoted} smudge %f"))?;
        // Long-running process filter: one daemon serves every blob of a git
        // operation, amortizing the per-file process cold start, repo open
        // and Argon2 (a shared batch salt). Clean/smudge above stay
        // configured: git >= 2.16 prefers `process`, older git ignores the
        // unknown key and falls back to them.
        self.set_raw_config(&format!("{f}.process"), &format!("{quoted} filter-process"))?;
        // Fail loudly (instead of committing plaintext) when the filter
        // cannot run, e.g. the binary was moved.
        self.set_raw_config(&format!("{f}.required"), "true")?;
        self.set_raw_config(
            &format!("diff.{}.textconv", gitattributes::FILTER_NAME),
            &format!("{quoted} diff"),
        )?;

        // 3. The legacy check hook is incompatible with filter mode. Look it up where install_hook
        //    would have put it (core.hooksPath-aware).
        let (hooks_dir, _) = self.hooks_dir()?;
        let hook = hooks_dir.join("pre-commit");
        if is_managed_hook(&hook)? {
            std::fs::remove_file(&hook)?;
            println!(
                "{} legacy pre-commit hook (incompatible with filter mode)",
                "Removed".yellow().bold()
            );
        } else if hook.exists() {
            warn!(
                "A foreign pre-commit hook exists at {}; it may block commits in filter mode.",
                hook.display()
            );
        }

        // 4. Decrypt the working tree where it is safe to do so.
        let (decrypted, needs_renormalize) = plan.as_ref().map_or((0, false), |plan| {
            (self.execute_migration(plan), plan.needs_renormalize)
        });

        println!(
            "{} git filter integration at {}",
            "Installed".green().bold(),
            self.path.display()
        );
        println!(
            "{}",
            "Working-tree files stay plaintext; git encrypts them on `git add` and decrypts on \
             checkout."
                .dimmed()
        );
        if !has_key {
            println!(
                "{}",
                "Run `git-se p` to set the password before staging files.".yellow()
            );
            return Ok(());
        }
        if decrypted > 0 {
            println!(
                "{} decrypted {decrypted} tracked file(s) in the working tree",
                "Auto".green().bold()
            );
        }
        if needs_renormalize {
            println!(
                "{}",
                "Some blobs need re-staging; run `git add --renormalize .` to encrypt them."
                    .yellow()
            );
        }
        Ok(())
    }

    /// Uninstall the git integration installed by `install` (either mode):
    /// remove the filter/textconv config, the managed `.gitattributes`
    /// block and the managed pre-commit hook, then restore the ciphertext
    /// working-tree copies of the tracked crypt files. Afterwards the
    /// repository behaves exactly as before the install: encryption and
    /// decryption are manual again (`git-se e` / `git-se d`).
    ///
    /// The crypt list, the password config and the salt cache are data, not
    /// integration — they are kept so manual operation (and a later
    /// reinstall) keeps working.
    pub fn uninstall(&self) -> Result<()> {
        let attr_path = self.path.join(".gitattributes");
        let attrs_installed = std::fs::read(&attr_path)
            .is_ok_and(|content| gitattributes::has_managed_block(&content));
        let (hooks_dir, _) = self.hooks_dir()?;
        let hook = hooks_dir.join("pre-commit");
        if !self.filter_installed() && !attrs_installed && !is_managed_hook(&hook)? {
            println!("No git-se integration found in {}.", self.path.display());
            return Ok(());
        }

        // The migration analysis MUST run while the filter config is still
        // in place: only then does `git diff HEAD` compare the worktree
        // through the clean filter and recognize the plaintext copy of a
        // ciphertext blob as clean, i.e. safe to re-checkout later. Dirty
        // files (staged or unstaged changes) keep their worktree copy — a
        // force-checkout would destroy uncommitted work.
        let migration = self.clean_crypt_paths();

        // 1. Unset the filter driver and textconv config written by install; missing keys are
        //    tolerated (partial installs).
        let f = format!("filter.{}", gitattributes::FILTER_NAME);
        for key in [
            format!("{f}.clean"),
            format!("{f}.smudge"),
            format!("{f}.process"),
            format!("{f}.required"),
            format!("diff.{}.textconv", gitattributes::FILTER_NAME),
        ] {
            self.unset_raw_config(&key)?;
        }

        // 2. Strip the managed .gitattributes block; delete the file when the block was its only
        //    content.
        match std::fs::read(&attr_path) {
            Ok(content) => {
                let rest = gitattributes::without_managed_block(&content);
                if is_blank(&rest) {
                    std::fs::remove_file(&attr_path)?;
                } else {
                    atomic_write(&attr_path, &rest)?;
                }
            },
            // A missing file means there is no block to strip (partial
            // installs are tolerated, like the config unsets above).
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {},
            Err(e) => return Err(e.into()),
        }

        // 3. Remove the managed pre-commit hook (hook-mode artifact); foreign hooks are never
        //    touched.
        if is_managed_hook(&hook)? {
            std::fs::remove_file(&hook)?;
            println!("{} pre-commit hook", "Removed".green().bold());
        } else if hook.exists() {
            warn!(
                "A foreign pre-commit hook exists at {}; left untouched.",
                hook.display()
            );
        }

        // 4. Restore the ciphertext worktree copies. With the filters and attributes gone, `git
        //    checkout --force HEAD` writes the raw ciphertext blobs back to the worktree.
        let mut restored = 0;
        match migration {
            Ok((to_restore, dirty)) => {
                restored = self.force_recheckout(&to_restore, "uninstall");
                if !dirty.is_empty() {
                    println!(
                        "{}",
                        format!(
                            "{} crypt-list file(s) with uncommitted changes stay plaintext; run \
                             `git-se e` to encrypt them before committing.",
                            dirty.len()
                        )
                        .yellow()
                    );
                }
            },
            Err(e) => warn!(
                "could not analyze the working tree ({e}); it was left untouched. Restore the \
                 ciphertext copies manually with `git checkout -- <paths>`."
            ),
        }

        println!(
            "{} git integration at {}",
            "Uninstalled".green().bold(),
            self.path.display()
        );
        if restored > 0 {
            println!(
                "{}",
                format!("Restored {restored} ciphertext working-tree file(s).").dimmed()
            );
        }
        Ok(())
    }

    /// Split the tracked crypt-list files into (clean, dirty) relative to
    /// HEAD, compared through the currently configured clean filter. Clean
    /// files are safe to force-checkout back to their raw ciphertext blobs
    /// once the filters are removed; dirty files carry staged or unstaged
    /// changes and must keep their worktree copy.
    fn clean_crypt_paths(&self) -> Result<(Vec<String>, Vec<String>)> {
        let mut candidates = Vec::new();
        if !self.conf.crypt_list.is_empty() && self.head_exists()? {
            let head = self.head_tree_blobs()?;
            if !head.is_empty() {
                let coverage = CryptCoverage::new(&self.conf.crypt_list);
                let index = self.index_blobs()?;
                candidates = head
                    .keys()
                    // Only files that are both committed and still tracked;
                    // a staged deletion must not resurface through the tree.
                    .filter(|p| index.contains_key(*p))
                    .map(|p| String::from_utf8_lossy(p).into_owned())
                    .filter(|rel| coverage.covers(rel))
                    .collect();
            }
        }

        // `git diff --name-only -z HEAD` lists everything that differs from
        // HEAD (staged and unstaged alike), so staged changes can never be
        // reset by the later force-checkout. One chunked invocation covers
        // any file count, unlike a per-file `git diff --quiet`.
        let mut dirty = HashSet::new();
        for chunk in candidates.chunks(64) {
            let mut args: Vec<&str> = vec!["diff", "--name-only", "-z", "HEAD", "--"];
            args.extend(chunk.iter().map(String::as_str));
            for path in nul_records(&self.run_with_output_bytes(&args)?) {
                dirty.insert(String::from_utf8_lossy(path).into_owned());
            }
        }
        Ok(candidates.into_iter().partition(|rel| !dirty.contains(rel)))
    }

    /// Refresh the managed `.gitattributes` block after crypt-list changes.
    ///
    /// No-op unless the block already exists (i.e. filter mode is active);
    /// the hook-only workflow never touches `.gitattributes`. Reading is
    /// byte-oriented like the other touchpoints, so non-UTF-8 pattern lines
    /// are preserved instead of aborting the refresh.
    pub fn refresh_gitattributes(&self) -> Result<()> {
        let attr_path = self.path.join(".gitattributes");
        let content = match std::fs::read(&attr_path) {
            Ok(content) => content,
            // A missing .gitattributes means filter mode is not active here.
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
            Err(e) => return Err(e.into()),
        };
        if !gitattributes::has_managed_block(&content) {
            return Ok(());
        }
        let updated = gitattributes::with_managed_block(&content, &self.filter_patterns());
        if updated != content {
            atomic_write(&attr_path, &updated)?;
        }
        Ok(())
    }

    /// Final gitignore-style patterns for the crypt list: directory entries
    /// get a `/**` suffix (a bare directory pattern does not cascade to its
    /// contents in `.gitattributes`).
    fn filter_patterns(&self) -> Vec<String> {
        self.conf
            .crypt_list
            .iter()
            .map(|entry| {
                // The `/**` suffix is a real glob and must stay inside the
                // quotes when the path itself needs quoting, so it is passed
                // as a suffix rather than appended to the escaped pattern.
                if self.path.join(entry).is_dir() {
                    gitattributes::escape_pattern(entry, "/**")
                } else {
                    gitattributes::escape_pattern(entry, "")
                }
            })
            .collect()
    }

    /// Transcrypt-style migration analysis at install time, over tracked
    /// crypt-list files whose worktree copy still equals the committed blob
    /// byte-for-byte (typical right after a clone, before any filter was
    /// installed). See [`MigrationPlan`] for the outcomes; executing the
    /// plan happens in [`Repo::execute_migration`].
    ///
    /// Unlike the pre-refactor code (one `git cat-file` spawn per file), the
    /// HEAD blobs are streamed through a single [`CatFileBatch`] session and
    /// compared chunk-by-chunk against the worktree files: a size mismatch
    /// classifies without reading the file body, and a matching size stops
    /// at the first differing chunk. No side of the compare is ever held in
    /// memory in full.
    fn migration_plan(&self) -> Result<MigrationPlan> {
        let mut plan = MigrationPlan::default();
        if self.conf.crypt_list.is_empty() {
            return Ok(plan);
        }
        let head = self.head_tree_blobs()?;
        if head.is_empty() {
            return Ok(plan); // unborn branch: nothing committed to migrate
        }
        let index = self.index_blobs()?;
        let coverage = CryptCoverage::new(&self.conf.crypt_list);
        let mut batch = CatFileBatch::spawn(&self.path)?;
        for (path, oid) in &head {
            // Only files that are both committed and still tracked; a staged
            // deletion must not resurface through the tree side.
            if !index.contains_key(path) {
                continue;
            }
            let rel = String::from_utf8_lossy(path).into_owned();
            if !coverage.covers(&rel) {
                continue;
            }
            let Some(mut stream) = batch.blob_stream(oid)? else {
                continue;
            };
            // The header prefix decides both magic checks; the payload body
            // is only consumed when a full compare is actually needed.
            let mut blob_head = vec![0u8; HEADER_LEN.min(stream.len())];
            stream.read_exact(&mut blob_head)?;
            let blob_encrypted = is_ciphertext(&blob_head);

            // An unreadable worktree copy has nothing to compare against.
            let opened = std::fs::File::open(self.path.join(&rel))
                .and_then(|file| file.metadata().map(|meta| (file, meta.len())));
            let (equal, worktree_encrypted) = match opened {
                Err(_) => {
                    stream.skip_to_end()?;
                    if !blob_encrypted {
                        plan.needs_renormalize = true;
                    }
                    continue;
                },
                Ok((mut file, file_len)) => {
                    // One prefix read feeds both the worktree magic check
                    // and the first compare segment.
                    let mut file_head = vec![0u8; blob_head.len()];
                    let filled = read_prefix(&mut file, &mut file_head)?;
                    let worktree_encrypted = is_ciphertext(&file_head[..filled]);
                    let equal = file_len == stream.len() as u64
                        && filled == blob_head.len()
                        && file_head == blob_head
                        && stream_eq_file(&mut stream, &mut file)?;
                    (equal, worktree_encrypted)
                },
            };
            stream.skip_to_end()?;

            if equal {
                // untouched since the last checkout: safe to re-smudge
                if blob_encrypted {
                    plan.to_decrypt.push(rel);
                } else {
                    // committed as plaintext before the filter existed
                    plan.needs_renormalize = true;
                }
            } else if blob_encrypted && !worktree_encrypted {
                // decrypted outside git (e.g. `git-se d`): the cached stat
                // no longer matches; renormalize refreshes it losslessly
                plan.needs_renormalize = true;
            } else if !blob_encrypted {
                // committed as plaintext before the filter existed
                plan.needs_renormalize = true;
            }
        }
        Ok(plan)
    }

    /// Run the force-checkout migration selected by `plan`: delete the
    /// worktree copies and `git checkout --force HEAD` them back so the
    /// smudge filter decrypts them. Returns the number of files decrypted.
    fn execute_migration(&self, plan: &MigrationPlan) -> usize {
        self.force_recheckout(&plan.to_decrypt, "install")
    }

    /// Delete the worktree copies of `paths` and `git checkout --force HEAD`
    /// them back, whatever that yields with the currently configured
    /// filters (smudge installed → plaintext, no filters → raw ciphertext
    /// blobs). `context` names the calling command in warnings. Returns the
    /// number of files restored.
    fn force_recheckout(&self, paths: &[String], context: &str) -> usize {
        // Chunk to stay clear of argv length limits on huge crypt lists.
        let mut restored = 0;
        'chunks: for chunk in paths.chunks(64) {
            for rel in chunk {
                let _ = std::fs::remove_file(self.path.join(rel));
            }
            let mut args: Vec<&str> = vec!["checkout", "--force", "HEAD", "--"];
            args.extend(chunk.iter().map(String::as_str));
            match Command::new("git")
                .current_dir(&self.path)
                .args(&args)
                .output()
            {
                Ok(out) if out.status.success() => restored += chunk.len(),
                Ok(out) => {
                    warn!(
                        "git checkout failed during {context}: {}",
                        String::from_utf8_lossy(&out.stderr)
                    );
                    break 'chunks;
                },
                Err(e) => {
                    warn!("failed to run git checkout during {context}: {e}");
                    break 'chunks;
                },
            }
        }
        restored
    }

    /// Whether any of `paths` (repo-relative) differ between the index and
    /// HEAD, via `git diff --cached --quiet`: exit code 1 means differences
    /// exist, 0 means none.
    fn has_staged_changes(&self, paths: &[String]) -> Result<bool> {
        for chunk in paths.chunks(64) {
            let out = Command::new("git")
                .current_dir(&self.path)
                .args(["diff", "--cached", "--quiet", "--"])
                .args(chunk)
                .output()?;
            match out.status.code() {
                Some(0) => {},
                Some(1) => return Ok(true),
                _ => {
                    return Err(Error::Git(
                        String::from_utf8_lossy(&out.stderr).into_owned(),
                    ));
                },
            }
        }
        Ok(false)
    }
}

/// Whether leftover `.gitattributes` content is blank (whitespace only):
/// uninstall's signal that the managed block was the file's only content and
/// the file itself can go.
///
/// Non-UTF-8 bytes always count as content — matching the byte-oriented
/// handling everywhere else — while for valid UTF-8 this is exactly
/// `str::trim().is_empty()`, preserving the pre-existing behavior.
fn is_blank(bytes: &[u8]) -> bool {
    std::str::from_utf8(bytes).is_ok_and(|s| s.trim().is_empty())
}

/// Print the check summary; `Err(FilesNotEncrypted)` when anything is plain.
fn report_check(not_encrypted: &[String], total: usize) -> Result<()> {
    if not_encrypted.is_empty() {
        println!(
            "\n{}: All {} files are encrypted.",
            "Check complete".bold(),
            total.to_string().green(),
        );
        return Ok(());
    }

    println!(
        "\n{} files are {}:",
        not_encrypted.len().to_string().yellow(),
        "NOT encrypted".yellow()
    );
    for f in not_encrypted {
        println!("  - {f}");
    }

    println!(
        "\n{}: {}/{} files encrypted",
        "Check complete".bold(),
        (total - not_encrypted.len()).to_string().green(),
        total,
    );

    Err(Error::FilesNotEncrypted(not_encrypted.len(), total))
}

/// Install-time migration analysis of the tracked crypt files (the
/// transcrypt-style re-smudge performed by [`Repo::install_filter`]).
#[derive(Default)]
struct MigrationPlan {
    /// Tracked crypt files whose worktree copy still equals the committed
    /// (encrypted) blob byte-for-byte — safe to delete and force-checkout so
    /// the smudge filter decrypts them.
    to_decrypt: Vec<String>,
    /// Whether `git add --renormalize .` should be recommended afterwards:
    /// some blob was committed as plaintext before the filter existed, or
    /// some file was decrypted outside of git and its cached stat is stale.
    needs_renormalize: bool,
}

